import type { DetailedApiContract, Project, ProjectApiContracts } from "@/types";

export function getSeedApiContracts(project: Project): ProjectApiContracts {
  if (project.id === "commercex") {
    return {
      contracts: commercexSeedApis,
    };
  }

  // Fallback for non-CommerceX projects
  return {
    contracts: (project.apiContracts || []).map((api, idx) => ({
      id: `api-${idx}-${api.service}`,
      service: api.service,
      module: api.service.replace("-service", ""),
      method: (api.method?.toUpperCase() as any) || "GET",
      path: api.endpoint,
      purpose: api.description,
      description: api.description,
      authentication: "JWT",
      authorization: ["ROLE_USER"],
      idempotency: {
        required: api.method === "POST",
        headerName: "Idempotency-Key",
        storageStrategy: "Redis",
        conflictBehavior: "Return previously cached response",
        ttl: "24 hours",
        notes: "Prevents duplicate requests.",
      },
      requestHeaders: [
        { id: "h1", name: "Authorization", value: "Bearer <JWT>", required: true, description: "Customer bearer token" },
        { id: "h2", name: "Content-Type", value: "application/json", required: true, description: "Payload format" },
      ],
      pathParameters: [],
      queryParameters: [],
      requestBody: {
        contentType: "application/json",
        jsonExample: api.request || "{}",
        description: "Payload",
      },
      responses: [
        { id: "r1", statusCode: 200, description: "Successful operation", contentType: "application/json", jsonExample: api.response || "{}" },
      ],
      errorResponses: [
        { id: "err1", statusCode: 400, errorCode: "INVALID_REQUEST", message: "Invalid payload parameters", description: "Validation failure", retryable: false, example: '{\n  "timestamp": "2026-08-10T10:00:00Z",\n  "status": 400,\n  "code": "INVALID_REQUEST",\n  "message": "Invalid payload parameters",\n  "path": "' + api.endpoint + '"\n}' },
      ],
      validationRules: [],
      pagination: { enabled: false, pageParam: "page", sizeParam: "size", sortParam: "sort", defaultSize: 20, maxSize: 100 },
      downstreamDependencies: [],
      communicationType: "SYNC REST",
      version: "v1",
      notes: "Auto-imported contract.",
    })),
  };
}

